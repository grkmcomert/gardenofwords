// Builds assets/game/perl-fixed.js: the wave/think/celebrate paintings with the
// stray third ear removed, as data URIs. JS ships inside the Shorebird patch;
// images under assets/game/images are native assets and cannot be patched.
const fs = require("fs");
const path = require("path");
const dir = __dirname;
const poses = ["wave", "think", "celebrate"];
const map = {};
for (const p of poses) map[p] = "data:image/webp;base64," + fs.readFileSync(path.join(dir, p + ".webp")).toString("base64");
const js = `// Generated by tooling/perl_fixed/make_js.cjs. Do not edit by hand.
(function () {
  var FIXED = ${JSON.stringify(map)};
  window.PERL_FIXED_POSES = FIXED;
  var PREFIX = "images/perl/";
  function swap(root) {
    var imgs = (root || document).querySelectorAll("img.perl-pose");
    for (var i = 0; i < imgs.length; i++) {
      var src = imgs[i].getAttribute("src") || "";
      if (src.indexOf(PREFIX) !== 0) continue;
      var pose = src.slice(PREFIX.length).replace(".webp", "");
      if (FIXED[pose]) imgs[i].setAttribute("src", FIXED[pose]);
    }
  }
  window.perlFixedSrc = function (pose) { return FIXED[pose] || ("images/perl/" + pose + ".webp"); };
  swap();
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", function () { swap(); });
})();
`;
fs.writeFileSync(path.join(dir, "..", "..", "assets", "game", "perl-fixed.js"), js);
console.log("perl-fixed.js", js.length, "bytes");
