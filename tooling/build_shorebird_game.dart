import 'dart:convert';
import 'dart:io';

/// Compiles the editable WebView game into Dart code that Shorebird can patch.
/// Run from the project root before every release, patch, or local Flutter run.
void main(List<String> args) {
  final root = Directory('assets/game').absolute;
  var html = File('${root.path}/index.html').readAsStringSync();
  final localScript = RegExp(
    r'''<script\b([^>]*?)\bsrc=["']([^"']+)["']([^>]*)>\s*</script>''',
    caseSensitive: false,
  );
  html = html.replaceAllMapped(localScript, (match) {
    final source = match[2]!;
    final uri = Uri.parse(source);
    if (uri.hasScheme || source.startsWith('//')) return match[0]!;
    final resolved = root.uri.resolve(source);
    if (!resolved.toString().startsWith(root.uri.toString())) {
      throw StateError('Game script escapes assets/game: $source');
    }
    final script = File.fromUri(resolved).readAsStringSync().replaceAll(
      RegExp('</script', caseSensitive: false),
      r'<\/script',
    );
    return '<script${match[1]}${match[3]}>\n$script\n</script>';
  });
  final localStyle = RegExp(
    r'''<link\b[^>]*\brel=["']stylesheet["'][^>]*\bhref=["']([^"']+)["'][^>]*>''',
    caseSensitive: false,
  );
  html = html.replaceAllMapped(localStyle, (match) {
    final source = match[1]!;
    final uri = Uri.parse(source);
    if (uri.hasScheme || source.startsWith('//')) return match[0]!;
    final resolved = root.uri.resolve(source);
    if (!resolved.toString().startsWith(root.uri.toString())) {
      throw StateError('Game stylesheet escapes assets/game: $source');
    }
    final css = File.fromUri(resolved).readAsStringSync().replaceAll(
      RegExp('</style', caseSensitive: false),
      r'<\/style',
    );
    return '<style>\n$css\n</style>';
  });

  final encoded = base64Encode(gzip.encode(utf8.encode(html)));
  final output = StringBuffer()
    ..writeln('// GENERATED by tooling/build_shorebird_game.dart. Do not edit.')
    ..writeln('// HTML, CSS and local JavaScript are Dart data for Shorebird.')
    ..writeln("import 'dart:convert';")
    ..writeln("import 'dart:io';")
    ..writeln()
    ..writeln('String decodeGameDocument() =>')
    ..writeln('    utf8.decode(gzip.decode(base64Decode(');
  for (var offset = 0; offset < encoded.length; offset += 100) {
    final end = (offset + 100).clamp(0, encoded.length);
    output.writeln("      '${encoded.substring(offset, end)}'");
  }
  output.writeln('    )));');

  final target = File('lib/generated/game_document.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() ||
        target.readAsStringSync() != output.toString()) {
      stderr.writeln(
        'Game bundle is stale. Run dart tooling/build_shorebird_game.dart.',
      );
      exitCode = 1;
    }
    return;
  }
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(output.toString());
  stdout.writeln(
    'Generated patchable game: ${utf8.encode(html).length} bytes, '
    '${encoded.length} base64 characters.',
  );
}
